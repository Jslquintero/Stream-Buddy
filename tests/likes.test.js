import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createLikesModule} from '../modules/likes/index.js';
import {defaultLikes} from '../modules/likes/config.js';
test('likes update immediately, autosave the full scoreboard and restore avatar URLs after restart',t=>{
  t.mock.timers.enable({apis:['setTimeout','Date'],now:10000});
  const dataDir=fs.mkdtempSync(path.resolve('tests/scratch-likes-'));let changes=0;
  const context={dataDir,changed(){changes++;},log(){}};const module=createLikesModule(context);
  t.after(()=>{module.close();for(const name of fs.readdirSync(dataDir))fs.unlinkSync(path.join(dataDir,name));fs.rmdirSync(dataDir);});
  module.receive({userId:'1',user:'Ana',count:5,avatar:'https://example.com/ana.jpg'},'test');
  assert.equal(changes,1);assert.equal(module.state().total,5);assert.equal(module.state().updatedAt,10000);
  module.receive({userId:'1',user:'Ana',count:3,avatar:''},'test');
  module.receive({userId:'2',user:'Luis',count:9,avatar:'javascript:alert(1)'},'test');
  assert.equal(module.state().ranking[0].id,'2');assert.equal(module.state().ranking[0].avatar,'');
  t.mock.timers.tick(1000);
  const reopened=createLikesModule(context);t.after(()=>reopened.close());
  assert.equal(reopened.state().savedAt,11000);assert.equal(reopened.state().total,17);
  assert.equal(reopened.state().ranking[1].avatar,'https://example.com/ana.jpg');
  reopened.save({...defaultLikes,limit:1});assert.equal(reopened.state().ranking.length,1);assert.equal(reopened.scoreboard().users.length,2);
});
test('likes rank stable user identities, deduplicate events and persist settings and counts',t=>{
  const dataDir=fs.mkdtempSync(path.resolve('tests/scratch-likes-'));
  const context={dataDir,changed(){},log(){}};const module=createLikesModule(context);
  t.after(()=>{module.close();for(const name of fs.readdirSync(dataDir))fs.unlinkSync(path.join(dataDir,name));fs.rmdirSync(dataDir);});
  module.receive({userId:'1',user:'Ana',count:10,messageId:'a'},'test');
  module.receive({userId:'2',user:'Ana',count:20,messageId:'b'},'test');
  assert.equal(module.receive({userId:'2',user:'Ana',count:20,messageId:'b'},'test'),false);
  module.receive({userId:'1',user:'Ana nueva',count:15,messageId:'c'},'test');
  assert.deepEqual(module.state().ranking.map(u=>u.likes),[25,20]);assert.equal(module.state().ranking[0].name,'Ana nueva');
  assert.equal(module.receive({userId:'3',count:-1},'test'),false);
  module.save({...defaultLikes,title:'Mis likes',limit:1,opacity:0});module.close();
  const reopened=createLikesModule(context);t.after(()=>reopened.close());
  assert.equal(reopened.state().total,45);assert.equal(reopened.state().participants,2);assert.equal(reopened.state().ranking.length,1);
  assert.equal(reopened.state().config.title,'Mis likes');
  assert.equal(reopened.receive({userId:'1',count:15,messageId:'c'},'test'),false);
  assert.throws(()=>reopened.save({...defaultLikes,limit:200}));assert.equal(reopened.state().config.title,'Mis likes');
  reopened.receive({userId:'3',user:'Luis',count:3},'another');assert.equal(reopened.state().total,3);
  reopened.reset();assert.equal(reopened.state().total,0);assert.equal(reopened.state().config.title,'Mis likes');
});
