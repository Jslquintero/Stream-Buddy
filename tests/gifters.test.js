import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createGiftersModule} from '../modules/gifters/index.js';
import {defaultGifters,validateGifters} from '../modules/gifters/config.js';
test('gifters migrate old designs and validate custom styles, metrics and CSS',()=>{
  const {style,showTitle,customCss,rgbNames,animateNames,pulseGifts,metric,...old}=defaultGifters;
  assert.deepEqual(validateGifters(old),defaultGifters);
  const custom={...defaultGifters,style:'medals',position:'bottom-left',showTitle:false,metric:'diamonds',customCss:'.gifters-name { color: red; }'};
  assert.deepEqual(validateGifters(custom),custom);
  assert.throws(()=>validateGifters({...custom,customCss:'.gifters-name {'}));
  assert.throws(()=>validateGifters({...custom,style:'unknown'}));
  assert.throws(()=>validateGifters({...custom,metric:'unknown'}));
  assert.throws(()=>validateGifters({...custom,pulseGifts:'true'}));
});
test('gifters update immediately, autosave the full scoreboard and restore avatar URLs after restart',t=>{
  t.mock.timers.enable({apis:['setTimeout','Date'],now:10000});
  const dataDir=fs.mkdtempSync(path.resolve('tests/scratch-gifters-'));let changes=0;
  const context={dataDir,changed(){changes++;},log(){}};const module=createGiftersModule(context);
  t.after(()=>{module.close();for(const name of fs.readdirSync(dataDir))fs.unlinkSync(path.join(dataDir,name));fs.rmdirSync(dataDir);});
  module.receive({userId:'1',user:'Ana',count:5,diamonds:90,gift:'Rosa',avatar:'https://example.com/ana.jpg'},'test');
  assert.equal(changes,1);assert.equal(module.state().total,5);assert.equal(module.state().totalDiamonds,90);assert.equal(module.state().updatedAt,10000);
  module.receive({userId:'1',user:'Ana',count:3,diamonds:5,gift:'Corazón',avatar:''},'test');
  module.receive({userId:'2',user:'Luis',count:9,diamonds:45,gift:'León',avatar:'javascript:alert(1)'},'test');
  assert.equal(module.state().ranking[0].id,'2');assert.equal(module.state().ranking[0].avatar,'');assert.equal(module.state().ranking[0].lastGift,'León');
  t.mock.timers.tick(1000);
  const reopened=createGiftersModule(context);t.after(()=>reopened.close());
  assert.equal(reopened.state().savedAt,11000);assert.equal(reopened.state().total,17);assert.equal(reopened.state().totalDiamonds,140);
  assert.equal(reopened.state().ranking[1].avatar,'https://example.com/ana.jpg');
  assert.equal(reopened.state().ranking[1].lastGift,'Corazón');
  reopened.save({...defaultGifters,limit:1});assert.equal(reopened.state().ranking.length,1);assert.equal(reopened.scoreboard().users.length,2);
  reopened.save({...defaultGifters,metric:'diamonds',limit:1});assert.equal(reopened.state().ranking[0].id,'1');assert.equal(reopened.state().total,140);
});
test('gifters rank stable user identities, deduplicate events and persist settings and counts',t=>{
  const dataDir=fs.mkdtempSync(path.resolve('tests/scratch-gifters-'));
  const context={dataDir,changed(){},log(){}};const module=createGiftersModule(context);
  t.after(()=>{module.close();for(const name of fs.readdirSync(dataDir))fs.unlinkSync(path.join(dataDir,name));fs.rmdirSync(dataDir);});
  module.receive({userId:'1',user:'Ana',count:10,diamonds:20,messageId:'a'},'test');
  module.receive({userId:'2',user:'Ana',count:20,diamonds:40,messageId:'b'},'test');
  assert.equal(module.receive({userId:'2',user:'Ana',count:20,diamonds:40,messageId:'b'},'test'),false);
  module.receive({userId:'1',user:'Ana nueva',count:15,diamonds:30,messageId:'c'},'test');
  assert.deepEqual(module.state().ranking.map(u=>u.gifts),[25,20]);assert.equal(module.state().ranking[0].name,'Ana nueva');
  assert.equal(module.state().ranking[0].diamonds,50);assert.equal(module.state().totalDiamonds,90);
  assert.equal(module.receive({userId:'3',count:-1},'test'),false);assert.equal(module.receive({userId:'3',count:1,diamonds:-5},'test'),true);
  module.save({...defaultGifters,title:'Mis gifters',limit:1,opacity:0,rgbNames:true,animateNames:true,pulseGifts:true});module.close();
  const reopened=createGiftersModule(context);t.after(()=>reopened.close());
  assert.equal(reopened.state().total,46);assert.equal(reopened.state().participants,3);assert.equal(reopened.state().ranking.length,1);
  assert.equal(reopened.state().config.title,'Mis gifters');
  for(const key of ['rgbNames','animateNames','pulseGifts'])assert.equal(reopened.state().config[key],true);
  assert.equal(reopened.receive({userId:'1',count:15,diamonds:30,messageId:'c'},'test'),false);
  assert.throws(()=>reopened.save({...defaultGifters,limit:200}));assert.equal(reopened.state().config.title,'Mis gifters');
  reopened.receive({userId:'4',user:'Luis',count:3,diamonds:4},'another');assert.equal(reopened.state().total,3);assert.equal(reopened.state().participants,1);
  reopened.reset();assert.equal(reopened.state().total,0);assert.equal(reopened.state().config.title,'Mis gifters');
});
