test('live output has transparent window interiors in every theme, without editor placeholders', async t => {
 const dom=new JSDOM('<div id="root"></div>',{url:'http://127.0.0.1:17900/?layout-output=1#tiktok.studio',runScripts:'outside-only',pretendToBeVisual:true});t.after(()=>dom.window.close());
 const {window}=dom;let stream;
 window.EventSource=class{constructor(){stream=this;}close(){}};
 window.ResizeObserver=class{observe(){}disconnect(){}};
 Object.defineProperty(window.HTMLElement.prototype,'clientWidth',{get(){return this.classList.contains('layout-canvas')?640:0;}});
 Object.defineProperty(window.HTMLElement.prototype,'clientHeight',{get(){return this.classList.contains('layout-canvas')?360:0;}});
 const html=fs.readFileSync(new URL('../dist/index.html',import.meta.url),'utf8');
 const asset=html.match(/src="([^"]+\.js)"/)[1];
 window.eval(fs.readFileSync(new URL('../dist'+asset,import.meta.url),'utf8'));
 await until(()=>stream);
 const {createVerticalLayout,themes,createIconRow}=await import('../shared/layout.js');
 for(const theme of Object.keys(themes)){
   const layout={...createVerticalLayout('gaming',theme),transparent:false,backgroundMode:'image',backgroundImage:'data:image/png;base64,aGVsbG8=',backgroundFit:'contain'};
   layout.elements.push(createIconRow('icons'));
   layout.elements.at(-1).icons[0].image='data:image/png;base64,aGVsbG8=';
   stream.onmessage({data:JSON.stringify({tools:{layout:{document:layout}}})});
   await until(()=>window.document.querySelector('.theme-'+theme));
   const plane=window.document.querySelector('.layout-plane');
   assert.equal(plane.style.width,'1080px');assert.equal(plane.style.height,'1920px');
   assert.equal(plane.style.transform,'translate(-50%, -50%) scale(0.1875)',theme+' preserves portrait ratio in a landscape source');
   const background=plane.querySelector('.layout-background');assert.ok(background);
   assert.equal(background.querySelector('image').getAttribute('preserveAspectRatio'),'xMidYMid meet');
   assert.equal(background.querySelectorAll('mask rect[fill="black"]').length,4,'Background keeps every window opening transparent');
   assert.equal(window.document.querySelectorAll('.row-shortcut').length,6);
   assert.equal(window.document.querySelectorAll('.row-shortcut-arrow').length,theme==='xp'?6:0);
   assert.equal(window.document.querySelector('.layout-icon-row .xp-title,.layout-icon-row .layout-title'),null);
   if(theme==='xp')assert.equal(window.document.querySelectorAll('.task-tab').length,4,'Icon rows are not windows on the taskbar');
   if(theme==='xp'){
     const opening=background.querySelector('mask rect[fill="black"]'),element=layout.elements[0];
     assert.equal(Number(opening.getAttribute('x')),element.x*1080/100+3);
     assert.equal(Number(opening.getAttribute('y')),element.y*1920/100+29);
     assert.equal(Number(opening.getAttribute('width')),element.w*1080/100-6);
     assert.equal(Number(opening.getAttribute('height')),element.h*1920/100-32);
   }
   const contents=window.document.querySelectorAll('.xp-content,.layout-content');
   assert.ok(contents.length>=4);
   for(const content of contents){
     assert.equal(content.style.backgroundColor,'transparent',theme+' interior');
     assert.equal(content.parentElement.style.backgroundColor,'transparent',theme+' window');
   }
   assert.equal(window.document.querySelectorAll('.layout-source-placeholder,.layout-guides').length,0);
 }
});
